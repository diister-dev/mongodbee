import type {
  DatabaseState,
  SchemaContent,
  SchemasDefinition,
} from "../migration/types.ts";
import type { PrivacyPlan, PrivacyTarget } from "../privacy/plan.ts";
import { fieldsOf } from "../privacy/transform.ts";

export function docsOf(
  state: DatabaseState,
  target: PrivacyTarget,
): Record<string, unknown>[] {
  switch (target.bucket) {
    case "collections":
      return state.collections[target.collection]?.content ?? [];
    case "multiCollections":
      return (state.multiCollections[target.collection]?.content ?? [])
        .filter((d) => d._type === target.type);
    case "multiModels":
      return Object.values(state.multiModels)
        .filter((i) => i.modelType === target.collection)
        .flatMap((i) => i.content.filter((d) => d._type === target.type));
    case "scopedMultiCollections":
      return (state.scopedMultiCollections[target.collection]?.content ?? [])
        .filter((d) => d._type === target.type);
  }
}

export function bucketContent(
  state: DatabaseState,
  target: PrivacyTarget,
): Record<string, unknown>[] {
  switch (target.bucket) {
    case "collections":
      state.collections[target.collection] ??= { content: [] };
      return state.collections[target.collection].content;
    case "multiCollections":
      state.multiCollections[target.collection] ??= { content: [] };
      return state.multiCollections[target.collection].content;
    case "scopedMultiCollections":
      state.scopedMultiCollections[target.collection] ??= { content: [] };
      return state.scopedMultiCollections[target.collection].content;
    case "multiModels":
      throw new Error(
        "scenario: multi-model instances are not generated by shape",
      );
  }
}

export function resolveTargetKey(plan: PrivacyPlan, key: string): string {
  if (plan.targets.has(key)) return key;
  const matches = [...plan.targets.keys()].filter((k) => {
    const [, collection, type] = k.split("/");
    return key === collection || key === `${collection}/${type}` ||
      key === type;
  });
  if (matches.length === 1) return matches[0];
  if (matches.length === 0) {
    const bySpace = [...plan.targets.values()].filter((t) => t.space === key);
    const person = bySpace.find((t) => t.person);
    if (person) return person.key;
    if (bySpace.length === 1) return bySpace[0].key;
    if (bySpace.length > 1) {
      throw new Error(
        `scenario: ambiguous target "${key}" (${
          bySpace.map((t) => t.key).join(", ")
        })`,
      );
    }
    throw new Error(`scenario: unknown target "${key}"`);
  }
  throw new Error(
    `scenario: ambiguous target "${key}" (${matches.join(", ")})`,
  );
}

export function fieldsOfTarget(
  schemas: SchemasDefinition,
  target: PrivacyTarget,
): SchemaContent | undefined {
  return fieldsOf(schemas, target);
}

export function targetFields(
  schemas: SchemasDefinition,
  target: PrivacyTarget,
): SchemaContent {
  const fields = fieldsOf(schemas, target);
  if (!fields) {
    throw new Error(`scenario: no schema for target "${target.key}"`);
  }
  return fields;
}
